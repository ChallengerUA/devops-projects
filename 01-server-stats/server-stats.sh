#!/bin/bash
echo ""
echo "**********************************************************************************"
echo "======= MEMORY USAGE ======="
free -h
echo ""
echo "**********************************************************************************"
echo ""
echo "======= DISK SPACE ======="
df -h
echo ""
echo "**********************************************************************************"
echo ""
echo "======= CPU USAGE ======="
cpu=$(top -bn1 | grep "Cpu" | awk '{print 100 - $8}')
echo "CPU Usage: $cpu%"
echo ""
echo "**********************************************************************************"
echo ""
echo "======= Top 5 processes by CPU usage ======="
ps aux | sort -rnk3 | head -5
echo ""
echo "**********************************************************************************"
echo ""
echo "======= Top 5 processes by Memory usage ======="
ps aux | sort -rnk4 | head -5
echo ""
echo "**********************************************************************************"
echo ""
echo "======= OS version ======="
uname -a
echo ""
echo "**********************************************************************************"
echo ""
echo "======= Uptime & Load average ======="
uptime
echo ""
echo "**********************************************************************************"
echo ""
echo "======= Logged in users ======="
who
echo ""
echo "**********************************************************************************"
echo ""
